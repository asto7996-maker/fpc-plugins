def format_doc_for_bot(doc: LegalDoc, *, page: int = 1, page_size: int = 900) -> tuple[str, int]:
    """
    Готовит текст документа для VK (с пагинацией).
    Возвращает (текст_страницы, всего_страниц).
    """
    body = doc.body.strip()
    chunks: list[str] = []
    buf = ""
    for para in body.split("\n"):
        candidate = f"{buf}\n{para}".strip() if buf else para
        if len(candidate) > page_size and buf:
            chunks.append(buf.strip())
            buf = para
        else:
            buf = candidate
    if buf.strip():
        chunks.append(buf.strip())
    if not chunks:
        chunks = [""]

    total = len(chunks)
    page = max(1, min(page, total))
    chunk = chunks[page - 1]
    head = f"{doc.emoji}  {doc.title}"
    meta = f"стр. {page}/{total}  ·  обновлено {doc.updated}"
    text = f"{head}\n━━━━━━━━━━━━━━━━\n{meta}\n\n{chunk}"
    return text, total
