    async def _tempo_pause(self, a: float, b: float) -> None:
        """Пауза, масштабируемая текущим темпом (в турбо почти исчезает)."""
        f = self._tempo_factor()
        lo = max(0.0, a * f)
        hi = max(lo, b * f)
        if hi < 0.015:
            return
        await self._human_pause(max(0.01, lo), hi)

